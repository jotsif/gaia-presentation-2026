// Scene shader: per-vertex (Gouraud) lighting + per-vertex linear fog, optional
// PS1-style vertex snapping and affine (non perspective-correct) texture mapping.
// Future-city phase extras:
//  - emissive surfaces: vertex alpha < 1 marks neon (when sun_color.a is set), texture
//    alpha < 1 marks lit windows (strength amb_color.a)
//  - the "singularity wave": a growing circle (wave.xy centre, wave.z radius) that dissolves
//    the old world (mode 1) and reveals the city (mode 2), whose buildings rise out of the
//    ground near the front (rise.x = depth, anchored per 64 m city block or at rise.zw)
// Finale: the world collapses into a singularity (hole.xyz centre, hole.w = radius of the
// collapse front). Vertices behind the front spiral in, flatten into a disc and heat up.
static const char* SCENE_MSL =
"#include <metal_stdlib>\n"
"using namespace metal;\n"
"struct vs_params {\n"
"    float4x4 mvp;\n"
"    float4x4 model;\n"
"    float4 cam_pos;     // xyz, w = fog start\n"
"    float4 light_dir;   // xyz (towards the sun), w = fog end\n"
"    float4 fog_color;   // rgb, a = unlit flag\n"
"    float4 snap;        // xy = half target resolution, z = jitter on, w = affine on\n"
"    float4 tint;        // rgb paint colour, a = tint enabled\n"
"    float4 sun_color;   // rgb direct light, a = emissive vertices enabled\n"
"    float4 amb_color;   // rgb ambient light, a = lit-window strength\n"
"    float4 wave;        // xy = centre (world xz), z = radius, w = mode (0 off, 1 old world, 2 new world)\n"
"    float4 rise;        // x = sink depth, y = fixed anchor on, zw = anchor xz\n"
"    float4 misc;        // x = neon strength, y = alpha multiplier (unlit draws)\n"
"    float4x4 vp;        // view-projection (used when vertices are displaced in world space)\n"
"    float4 hole;        // xyz = singularity (world), w = collapse front radius\n"
"    float4 hole2;       // x = collapse on, y = total swirl (rad), z = darken unlit (sky)\n"
"};\n"
"struct vs_in {\n"
"    float3 pos   [[attribute(0)]];\n"
"    float3 nrm   [[attribute(1)]];\n"
"    float2 uv    [[attribute(2)]];\n"
"    float4 color [[attribute(3)]];\n"
"};\n"
"struct vs_out {\n"
"    float4 pos [[position]];\n"
"    float4 color;\n"
"    float3 raw;\n"
"    float3 wpos;\n"
"    float2 uv;\n"
"    float2 uv_affine [[center_no_perspective]];\n"
"    float fog;\n"
"    float emis;\n"
"    float affine [[flat]];\n"
"    float3 fog_color [[flat]];\n"
"    float4 wave [[flat]];\n"
"    float2 glow [[flat]];   // x = neon, y = windows\n"
"    float heat;\n"
"};\n"
"vertex vs_out vs_scene(vs_in in [[stage_in]], constant vs_params& p [[buffer(0)]]) {\n"
"    vs_out o;\n"
"    float3 lpos = in.pos;\n"
"    float4 wp = p.model * float4(lpos, 1.0);\n"
"    if (p.wave.w > 1.5 && p.rise.x > 0.0) {\n"
"        float2 anchor = (p.rise.y > 0.5) ? p.rise.zw : (floor(wp.xz / 64.0) + 0.5) * 64.0;\n"
"        float d = length(anchor - p.wave.xy);\n"
"        float grow = 1.0 - smoothstep(p.wave.z - 260.0, p.wave.z, d);\n"
"        float sink = (1.0 - grow) * p.rise.x;\n"
"        lpos.y -= sink;\n"
"        wp.y -= sink;\n"
"    }\n"
"    float3 wave_pos = wp.xyz;\n"
"    float heat = 0.0;\n"
"    float4 clip;\n"
"    if (p.hole2.x > 0.5) {\n"
"        float3 rel = wp.xyz - p.hole.xyz;\n"
"        float d = length(rel);\n"
"        float h = fract(sin(dot(floor(wp.xz / 24.0), float2(12.9898, 78.233))) * 43758.5453);\n"
"        float u = clamp((p.hole.w - d * (0.9 + 0.2 * h)) / (260.0 + 0.45 * d), 0.0, 1.0);\n"
"        float a = p.hole2.y * u * u;\n"
"        float ca = cos(a), sa = sin(a);\n"
"        rel = float3(ca * rel.x - sa * rel.z, rel.y * (1.0 - u), sa * rel.x + ca * rel.z);\n"
"        wp.xyz = p.hole.xyz + rel * (1.0 - u) * (1.0 - u);\n"
"        heat = u;\n"
"        clip = p.vp * float4(wp.xyz, 1.0);\n"
"    } else {\n"
"        clip = p.mvp * float4(lpos, 1.0);\n"
"    }\n"
"    if (p.snap.z > 0.5 && clip.w > 0.05) {\n"
"        float2 ndc = clip.xy / clip.w;\n"
"        ndc = floor(ndc * p.snap.xy + 0.5) / p.snap.xy;\n"
"        clip.xy = ndc * clip.w;\n"
"    }\n"
"    o.pos = clip;\n"
"    float4 c = in.color;\n"
"    o.raw = c.rgb;\n"
"    o.emis = 0.0;\n"
"    if (p.tint.a > 0.5) {\n"
"        c.rgb = mix(c.rgb * p.tint.rgb, c.rgb, c.a);\n"
"        c.a = 1.0;\n"
"    } else if (p.sun_color.a > 0.5) {\n"
"        o.emis = 1.0 - c.a;\n"
"        c.a = 1.0;\n"
"    }\n"
"    if (p.fog_color.a < 0.5) {\n"
"        float3 n = normalize((p.model * float4(in.nrm, 0.0)).xyz);\n"
"        float d = max(dot(n, p.light_dir.xyz), 0.0);\n"
"        float sky = 0.5 + 0.5 * n.y;\n"
"        c.rgb *= p.amb_color.rgb * (0.38 + 0.14 * sky) + p.sun_color.rgb * (0.72 * d);\n"
"        float dist = length(wp.xyz - p.cam_pos.xyz);\n"
"        o.fog = clamp((dist - p.cam_pos.w) / (p.light_dir.w - p.cam_pos.w), 0.0, 1.0);\n"
"    } else {\n"
"        o.fog = 0.0;\n"
"        c.a *= p.misc.y;\n"
"        c.rgb *= 1.0 - p.hole2.z;\n"
"    }\n"
"    o.color = c;\n"
"    o.wpos = wave_pos;\n"
"    o.heat = heat;\n"
"    o.uv = in.uv;\n"
"    o.uv_affine = in.uv;\n"
"    o.affine = p.snap.w;\n"
"    o.fog_color = p.fog_color.rgb;\n"
"    o.wave = p.wave;\n"
"    o.glow = float2(p.misc.x, p.amb_color.a);\n"
"    return o;\n"
"}\n"
"fragment float4 fs_scene(vs_out in [[stage_in]], texture2d<float> tex [[texture(0)]], sampler smp [[sampler(0)]]) {\n"
"    float edge_glow = 0.0;\n"
"    if (in.wave.w > 0.5) {\n"
"        float dist = length(in.wpos.xz - in.wave.xy);\n"
"        float2 cell = floor(in.wpos.xz / 3.0) + floor(in.wpos.y / 3.0) * 17.0;\n"
"        float h = fract(sin(dot(cell, float2(12.9898, 78.233))) * 43758.5453);\n"
"        float edge = in.wave.z - h * 26.0;\n"
"        if ((in.wave.w < 1.5) ? (dist < edge) : (dist >= edge)) discard_fragment();\n"
"        edge_glow = 1.0 - smoothstep(0.0, 34.0, abs(dist - in.wave.z + 13.0));\n"
"    }\n"
"    float2 uv = (in.affine > 0.5) ? in.uv_affine : in.uv;\n"
"    float4 t = tex.sample(smp, uv);\n"
"    float win = (1.0 - t.a) * step(0.001, in.glow.y);\n"
"    float3 base = mix(t.rgb, float3(0.16, 0.20, 0.30), win * (1.0 - in.glow.y));\n"
"    float4 c = float4(base, t.a) * in.color;\n"
"    float em = max(win * in.glow.y, in.emis * in.glow.x);\n"
"    if (em > 0.0) {\n"
"        float3 e = t.rgb * mix(float3(1.0), in.raw, in.emis) * 1.25;\n"
"        c.rgb = mix(c.rgb, e, em);\n"
"        c.a = 1.0;\n"
"    }\n"
"    c.rgb = mix(c.rgb, in.fog_color, in.fog * (1.0 - 0.55 * em) * (1.0 - in.heat));\n"
"    if (in.heat > 0.0) {\n"
"        // infalling matter keeps its colours, glows orange, and only turns white-hot at the core\n"
"        float3 orange = float3(1.0, 0.45, 0.12);\n"
"        float3 glowing = c.rgb * orange * 1.8 + orange * 0.25;\n"
"        c.rgb = mix(c.rgb, glowing, smoothstep(0.05, 0.5, in.heat));\n"
"        c.rgb = mix(c.rgb, float3(1.0, 0.93, 0.82), smoothstep(0.7, 0.97, in.heat));\n"
"    }\n"
"    c.rgb += edge_glow * float3(0.25, 0.95, 1.0) * 0.85;\n"
"    return c;\n"
"}\n";

// Display shader: upscales the low-res render target with nearest filtering and
// optionally quantizes to 15-bit colour with a 4x4 ordered dither.
static const char* DISPLAY_MSL =
"#include <metal_stdlib>\n"
"using namespace metal;\n"
"struct disp_params {\n"
"    float4 res;     // xy = source resolution\n"
"    float4 flags;   // x = dither on, y = scanlines strength, z = title dim, w = fade to black\n"
"    float4 hole;    // xy = singularity (uv), z = event horizon radius (screen heights), w = glow\n"
"    float4 hole2;   // x = aspect, y = white flash, z = lensing strength, w = final fade to black\n"
"};\n"
"struct vs_out {\n"
"    float4 pos [[position]];\n"
"    float2 uv;\n"
"};\n"
"vertex vs_out vs_display(uint vid [[vertex_id]]) {\n"
"    float2 p = float2((vid << 1) & 2, vid & 2);\n"
"    vs_out o;\n"
"    o.pos = float4(p * 2.0 - 1.0, 0.0, 1.0);\n"
"    o.uv = float2(p.x, 1.0 - p.y);\n"
"    return o;\n"
"}\n"
"constant float BAYER[16] = { 0.0, 8.0, 2.0, 10.0, 12.0, 4.0, 14.0, 6.0, 3.0, 11.0, 1.0, 9.0, 15.0, 7.0, 13.0, 5.0 };\n"
"fragment float4 fs_display(vs_out in [[stage_in]], texture2d<float> tex [[texture(0)]], sampler smp [[sampler(0)]],\n"
"                           constant disp_params& p [[buffer(0)]]) {\n"
"    float2 uv = in.uv;\n"
"    float horizon = 1.0;\n"
"    float3 add = float3(0.0);\n"
"    if (p.hole.z > 0.0) {\n"
"        // gravitational lensing around a black event horizon with a hot photon ring\n"
"        float2 asp = float2(p.hole2.x, 1.0);\n"
"        float2 d = (uv - p.hole.xy) * asp;\n"
"        float r = max(length(d), 1e-4);\n"
"        float rs = p.hole.z;\n"
"        uv -= (d / r) * (p.hole2.z * rs * rs / r) / asp;\n"
"        uv = clamp(uv, float2(0.0), float2(1.0));\n"
"        horizon = smoothstep(rs * 0.92, rs * 1.04, r);\n"
"        float ring = exp(-pow((r - rs * 1.32) / (rs * 0.16), 2.0));\n"
"        float halo = exp(-r / (rs * 2.5 + 0.01));\n"
"        add = p.hole.w * (ring * float3(1.0, 0.78, 0.5) + 0.45 * halo * float3(1.0, 0.6, 0.3)) * horizon;\n"
"    }\n"
"    float3 c = tex.sample(smp, uv).rgb * horizon + add;\n"
"    c = mix(c, float3(1.0), p.hole2.y);\n"
"    c *= 1.0 - p.hole2.w;\n"
"    float2 src = in.uv * p.res.xy;\n"
"    if (p.flags.x > 0.5) {\n"
"        int2 px = int2(src) & 3;\n"
"        float b = BAYER[px.y * 4 + px.x] / 16.0 - 0.5;\n"
"        c = clamp(floor(c * 31.0 + 0.5 + b * 0.9) / 31.0, 0.0, 1.0);\n"
"    }\n"
"    if (p.flags.y > 0.0) {\n"
"        float f = fract(src.y);\n"
"        c *= 1.0 - p.flags.y * smoothstep(0.55, 1.0, abs(f - 0.5) * 2.0);\n"
"    }\n"
"    if (p.flags.z > 0.0) {\n"
"        float vig = smoothstep(0.25, 0.8, length(in.uv - 0.5));\n"
"        c *= 1.0 - p.flags.z * (0.45 + 0.45 * vig);\n"
"    }\n"
"    c *= 1.0 - p.flags.w;\n"
"    return float4(c, 1.0);\n"
"}\n";

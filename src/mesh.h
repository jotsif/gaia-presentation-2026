// CPU-side mesh building (flat shaded, non-indexed triangle soups + optional indices).
#pragma once
#include <stdint.h>
#include "mathx.h"

typedef struct {
    float pos[3];
    float nrm[3];
    float uv[2];
    uint32_t color;     // RGBA8; for car meshes alpha==0 marks 'tintable' (body paint) vertices
} vertex_t;

typedef struct {
    vertex_t* v;
    int count, cap;
    uint32_t* idx;
    int icount, icap;
} mesh_t;

#define RGBA(r,g,b,a) ((uint32_t)(r) | ((uint32_t)(g) << 8) | ((uint32_t)(b) << 16) | ((uint32_t)(a) << 24))
#define RGB(r,g,b) RGBA(r,g,b,255)

// scale used for automatic planar texture coordinates (texture repeats per 1/scale meters)
extern float mesh_uv_scale;

void mesh_free(mesh_t* m);
void mesh_vertex(mesh_t* m, vec3 p, vec3 n, float u, float v, uint32_t col);
void mesh_index(mesh_t* m, uint32_t i);

// Flat-shaded triangle; the face normal is flipped to point along 'hint' (if hint is non-zero).
// UVs are generated by planar projection along the dominant normal axis.
void mesh_tri(mesh_t* m, vec3 a, vec3 b, vec3 c, vec3 hint, uint32_t col);
// Quad a-b-c-d (ring order), split into two flat triangles.
void mesh_quad(mesh_t* m, vec3 a, vec3 b, vec3 c, vec3 d, vec3 hint, uint32_t col);
// Quad with explicit normal and per-corner UVs.
void mesh_quad_uv(mesh_t* m, vec3 a, vec3 b, vec3 c, vec3 d, const float uv[4][2], vec3 n, uint32_t col);
// Convex 'hexahedron' given 8 corners: bottom ring 0..3 then top ring 4..7 (same ring order).
void mesh_hexa(mesh_t* m, const vec3 c[8], uint32_t col);
void mesh_box(mesh_t* m, vec3 mn, vec3 mx, uint32_t col);
// cylinder along the x axis (wheels)
void mesh_cyl_x(mesh_t* m, vec3 center, float radius, float half_width, int sides, uint32_t col);
void mesh_cone(mesh_t* m, vec3 base, float radius, float height, int sides, uint32_t col);
// low-poly ellipsoid
void mesh_blob(mesh_t* m, vec3 c, float rx, float ry, float rz, int sides, uint32_t col);
